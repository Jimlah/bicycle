import puppeteer from 'puppeteer-core'
const t0 = Date.now()
const log = (m) => console.log(`${((Date.now() - t0) / 1000).toFixed(1)}s ${m}`)
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new',
  args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--allow-file-access-from-files'], protocolTimeout: 400000 })
const page = await browser.newPage()
await page.setViewport({ width: 1280, height: 800 })
const errs = []
page.on('pageerror', (e) => errs.push('pageerror: ' + e.message))
page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()) })
await page.goto('file:///Users/abdullahi/Herd/CAD/bicycle/bicycle.html', { waitUntil: 'load' })
await page.waitForFunction('window.__READY === true', { timeout: 180000 })
log('ready')
const clickRide = await page.evaluate(() => {
  const b = [...document.querySelectorAll('#dock .btn')].find((x) => x.textContent === 'Ride')
  if (!b) return false
  b.click(); return true
})
log('ride clicked ' + clickRide)
await new Promise((r) => setTimeout(r, 1500))
await page.screenshot({ path: '/tmp/ride-0.png' })
await page.keyboard.down('KeyW')
await new Promise((r) => setTimeout(r, 2600))
const s1 = await page.evaluate(() => ({ speed: window.__RIDE.speed, crank: window.__RIDE.crankAng, bodies: Object.entries(window.__RIDE.bodies).map(([n, b]) => [n, b.translation().x.toFixed(0), b.translation().y.toFixed(0), isFinite(b.translation().x)]) }))
log('after pedal: ' + JSON.stringify(s1))
await page.screenshot({ path: '/tmp/ride-1.png' })
await page.keyboard.up('KeyW')
await page.keyboard.down('Space')
await new Promise((r) => setTimeout(r, 1200))
await page.keyboard.up('Space')
const s2 = await page.evaluate(() => ({ speed: window.__RIDE.speed, brake: window.__RIDE.brake }))
log('after brake: ' + JSON.stringify(s2))
await page.keyboard.down('KeyA')
await new Promise((r) => setTimeout(r, 1200))
await page.keyboard.up('KeyA')
const s3 = await page.evaluate(() => ({ steer: window.__RIDE.steer, speed: window.__RIDE.speed }))
log('after steer: ' + JSON.stringify(s3))
await page.screenshot({ path: '/tmp/ride-2.png' })
console.log('errors:', errs.slice(0, 8))
await browser.close()
